"""The run layout as JSON for clients that are not Python, such as scenario-lab.

Every name comes from the module that defines it (``exporters.artifact_paths``,
``storage.s3``, the stage graph), so a client generated from this output cannot
drift from what the pipeline writes. Run ``python -m coinjoin_pipeline.run_layout``
to print it; scenario-lab stores the output as ``shared/run-layout.json``.
"""

from __future__ import annotations

import json
import sys

from exporters import artifact_paths as paths

from .storage.s3 import RUN_ID_MAX_LENGTH, RUN_ID_RE

EMULATION_STAGE = "kubernetes-emulation"
BASELINE_STAGE = "coinjoin-analysis"
BLOCKSCI_STAGE = "blocksci"
REPORT_STAGE = "unified-report"
MAINNET_PRODUCER_STAGE = "mainnet-producer"

GENERATED_NOTE = "Generated by `python -m coinjoin_pipeline.run_layout` from coinjoin-pipeline; do not edit."


def run_layout() -> dict[str, object]:
    """Run IDs, marker directories, the files clients read and the directories each stage writes."""
    return {
        "$comment": GENERATED_NOTE,
        "runId": {"pattern": RUN_ID_RE.pattern, "maxLength": RUN_ID_MAX_LENGTH},
        "markers": [paths.KUBERNETES_MARKER_DIR, paths.PBS_MARKER_DIR],
        "files": {
            "dataset": f"{paths.REPORT_DIR}/{paths.LIQUIDITY_DATASET}",
            "scenario": paths.SCENARIO_FILE,
            "report": paths.REPORT_FILE,
            "postmix": paths.POSTMIX_SPENDS_FILE,
        },
        "artifacts": {
            "emulator": {"directories": [paths.EMULATOR_DIR], "stage": EMULATION_STAGE},
            "producer": {"directories": [paths.LOGS_DIR], "stage": MAINNET_PRODUCER_STAGE},
            "analysis": {
                "directories": [paths.COINJOIN_ANALYSIS_DIR, paths.COINJOIN_ANALYSIS_TOOLS_DIR],
                "stage": BASELINE_STAGE,
            },
            "blocksci": {
                "directories": [
                    paths.BLOCKSCI_ANALYSIS_DIR,
                    paths.BLOCKSCI_PARSE_DIR,
                    paths.BLOCKSCI_CUSTOM_ANALYSIS_DIR,
                    paths.BLOCKSCI_NOTEBOOKS_DIR,
                ],
                "stage": BLOCKSCI_STAGE,
            },
            "report": {"directories": [paths.REPORT_DIR], "stage": REPORT_STAGE},
        },
    }


def main() -> int:
    sys.stdout.write(json.dumps(run_layout(), indent=2) + "\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
